let LANG = "zh";

function t(key) {
  const pack = I18N[LANG] || I18N.zh;
  return pack[key] !== undefined ? pack[key] : (I18N.zh[key] !== undefined ? I18N.zh[key] : key);
}

/* 从 {zh, lo} 对象里取当前语言 */
function pick(value) {
  if (value === null || value === undefined) return "";
  if (typeof value === "string") return value;
  return value[LANG] !== undefined ? value[LANG] : (value.zh || "");
}

/* 占位符替换：fmt("第 {i} / {n} 题", {i:1, n:3}) */
function fmt(str, vars) {
  return String(str).replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
}
